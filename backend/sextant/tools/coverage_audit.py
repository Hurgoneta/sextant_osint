"""Global coverage audit, generated from the registries — never written by hand.

    python -m sextant.tools.coverage_audit                         # print Markdown
    python -m sextant.tools.coverage_audit --out ../docs/audit/global-coverage-audit.md

Reports, for a default installation (no API keys configured, no optional tools installed):
countries by coverage level and region; every country with its level; the platform registry by category and
by what this installation can search; every connector with its status and health; and the lists of what is
implemented, what needs credentials, what needs commercial access and what is unavailable.
"""

from __future__ import annotations

import argparse
import sys
from datetime import datetime, timezone
from pathlib import Path

from ..registry import connectors as REG
from ..registry import coverage_model as CM
from ..registry import discovered as D
from ..registry import platforms as P
from ..registry.health import HEALTH_TITLES

NAMED = ("RO SE HU DE FR IT ES PT NL BE AT DK FI NO IS IE PL CZ SK SI HR RS BA ME MK AL BG GR MD UA LT LV EE LU MT CY CH LI "
         "GB US CA NG GH KE ZA ET EG MA DZ TN TZ UG RW SN CI CM AO MZ ZM ZW BW NA MU MG CD CG SO SD SS IN PK BD JP KR CN BR "
         "AR AU NZ").split()


def table(head: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c).replace("|", "/") for c in r) + " |" for r in rows]
    return out


def build(cfg=None) -> str:
    REG.load_all()
    ctx = CM.CoverageContext(cfg)
    rows = CM.cached_rows(ctx)
    summ = CM.summary(ctx, rows)
    sov = sorted((r for r in rows if r["sovereign"]), key=lambda r: r["name"])
    by_code = {r["code"]: r for r in rows}
    now = datetime.now(timezone.utc).replace(microsecond=0).isoformat()
    tools = [n for n in ("maigret", "sherlock", "spiderfoot", "theharvester") if REG.REGISTRY[n].installed(cfg)[0]]
    setup = ("no API keys configured; optional tools installed: " + ", ".join(
        f"{t} ({'on' if ctx.states[t] == 'available' else 'off by default'})" for t in tools)) if tools \
        else "no API keys and no optional tools"
    L: list[str] = [f"# Global coverage audit — {now[:10]}", "",
                    f"Generated by `python -m sextant.tools.coverage_audit` at {now} from the registries. The configuration "
                    f"audited is this installation: {setup}. Configured keys raise these numbers, "
                    "and the Global Coverage screen always shows the live values.", "",
                    f"> {CM.SEARCH_DISCLAIMER}", ""]

    c = summ["countries"]
    L += ["## 1. Countries", "",
          f"* **{c['total']} sovereign states** in the registry (193 UN members + Holy See + State of Palestine), each an "
          f"individual entry; {c['territories']} territories listed separately (not counted).",
          f"* With at least one **country connector** (automated): **{c['with_country_connectors']}**",
          f"* With curated **official sources (links only)**: **{c['links_only']}**",
          f"* With **potential sources only** (discovered in maintained datasets, not reviewed): **{c['discovered_only']}**",
          f"* With **no connector and no known source**: **{c['none']}**", ""]
    L += table(["Region", "Countries", "Country connectors", "Links only", "Potential only", "None"],
               [[g["region"], g["countries"], g["connectors"], g["links"], g["discovered"], g["none"]] for g in c["by_region"]])
    L += ["", "Every sovereign state also gets the global sources: GLEIF (LEIs), Wikidata, OpenSanctions, ICIJ Offshore "
          "Leaks, GDELT news filtered by outlet country, DNS/RDAP for its ccTLD (RDAP where the registry offers it), "
          "RIPEstat for its IP space, offline phone-numbering metadata, and the platform registry.", ""]

    L += ["### Countries named in the requirement", ""]
    L += table(["Country", "Level", "Country connectors", "Official sources", "Potential", "Regional platforms", "ccTLD RDAP"],
               [[f"{by_code[k]['name']} ({k})", by_code[k]["level_title"],
                 ", ".join(ctx.country_connectors(k)) or "—", by_code[k]["curated_sources"], by_code[k]["discovered_sources"],
                 by_code[k]["regional_platforms"], "yes" if (by_code[k]["dns"] or {}).get("rdap") else "no"]
                for k in NAMED if k in by_code])
    L += ["", "### All 195 countries", ""]
    L += table(["Country", "Region", "Level", "Conn.", "Official", "Regional portals", "Potential", "Platforms"],
               [[f"{r['name']} ({r['code']})", r["region"], r["level"], r["connectors"], r["curated_sources"],
                 r.get("regional_sources", 0), r["discovered_sources"], r["regional_platforms"]] for r in sov])

    p = summ["platforms"]
    cat = P.catalog(ctx.states, ctx.adapters, include_imported=False)
    L += ["", "## 2. Platforms", "",
          f"* **{p['registered']:,} registered**: {p['curated']} curated with capability metadata + {p['imported']:,} "
          "known from the WhatsMyName, Maigret and Sherlock datasets.",
          f"* **Searchable in a normal run on this installation: {p['searchable']:,}** · more with SEARCH EVERYTHING "
          f"(Maigret beyond its top {p.get('maigret_top_n') or 500} sites): {p['by_status'].get('search_everything_only', 0):,} · "
          f"adult/dating sites off in Settings: {p['by_status'].get('adult_off', 0):,} · API key / subscription needed: "
          f"{p['api_only']} · not searchable here: {p['unavailable']:,} (manual links, no rule in the installed tools, "
          f"excluded by policy, no public profiles, shut down).",
          f"* Adapter site lists after Sextant's site policy (installed versions): Maigret "
          f"{p.get('adapter_sites', {}).get('maigret', 0):,} active sites, Sherlock {p.get('adapter_sites', {}).get('sherlock', 0):,}.",
          ""]
    L += table(["Status", "Platforms"], [[P.SEARCH_STATUS_TITLES[k], f"{v:,}"] for k, v in p["by_status"].items() if v])
    curated_by_cat: dict[str, dict[str, int]] = {}
    for d in cat["curated"]:
        curated_by_cat.setdefault(d["category_title"], {}).setdefault(d["search_status"], 0)
        curated_by_cat[d["category_title"]][d["search_status"]] += 1
    L += ["", "Curated platforms by category (searchable / total):", ""]
    L += table(["Category", "Searchable", "Total"],
               [[k, v.get("searchable", 0), sum(v.values())] for k, v in sorted(curated_by_cat.items())])

    L += ["", "## 3. Connectors", ""]
    groups: dict[str, list[str]] = {}
    for name, conn in sorted(REG.REGISTRY.items()):
        groups.setdefault(ctx.states[name], []).append(name)
    titles = {"available": "Implemented and ready (free, no key)", "disabled": "Implemented, off by default (opt-in)",
              "needs_credentials": "Implemented — needs a free API key / approval",
              "needs_subscription": "Implemented — needs commercial access (your subscription)",
              "not_installed": "Implemented adapter — external tool not installed",
              "catalog_only": "Unavailable — documented only (no public API; contact the provider)",
              "retired": "Unavailable — retired by the provider", "excluded": "Unavailable — excluded by policy",
              "manual": "Manual only (platform forbids automation)"}
    for st in ("available", "disabled", "needs_credentials", "needs_subscription", "not_installed", "catalog_only", "retired",
               "excluded", "manual"):
        names = groups.get(st, [])
        if not names:
            continue
        L += [f"### {titles[st]} — {len(names)}", ""]
        L += table(["Connector", "Category", "Countries", "Health", "Last verified"],
                   [[f"{REG.REGISTRY[n].manifest.title} (`{n}`)", REG.REGISTRY[n].manifest.category_title,
                     ", ".join(x for x in REG.REGISTRY[n].manifest.supported_countries) if
                     tuple(REG.REGISTRY[n].manifest.supported_countries) != ("*",) else "global",
                     (h := ctx.health(n))["title"], (h["last_verified"] or "—")[:10]] for n in names])
        L.append("")
    health: dict[str, int] = summ["connectors"]["by_health"]
    L += ["Health summary: " + ", ".join(f"{HEALTH_TITLES[k]} {v}" for k, v in sorted(health.items(), key=lambda kv: -kv[1])), ""]

    pub = summ["public_databases"]
    L += ["## 4. Public databases and datasets", "",
          f"* Official sources in the jurisdiction registry: **{pub['official_sources']}** ({pub['automated']} automated by "
          f"connectors, {pub['links_only']} links for the investigator).",
          f"* Potential sources discovered in maintained datasets: **{pub['discovered']:,}** "
          f"({', '.join(f'{v['title']}: {v['items']:,}' for v in D.dataset_info().values())}).",
          "* Link checks of official sources (last completed run "
          f"{(pub['links_checked_at'] or 'never')[:10]}; sources added since show as not checked): "
          + ", ".join(f"{k.replace('_', ' ')} {v}" for k, v in pub["link_checks"].items()),
          "", "## 5. Commercial providers", "",
          f"* Configured: {summ['commercial']['configured']} · implemented but not configured: "
          f"{summ['commercial']['not_configured']} · documented only (contact provider): {summ['commercial']['catalog_only']}.",
          f"* Commercial providers listed per country (links; subscription required, never bypassed): "
          f"{summ['commercial'].get('providers_listed', 0)} providers covering {summ['commercial'].get('countries_with_providers', 0)} countries.",
          "", "## 6. What this audit does not claim", "",
          "* Registered is not searchable: platform and source counts are split by what this installation can query.",
          "* Potential sources are leads from datasets (GLEIF, OpenSanctions, Wikidata, IANA, RIRs, GDELT); nobody has "
          "reviewed their search capabilities.",
          "* Private accounts, private messages, login-only content and paid content are never accessed.", ""]
    return "\n".join(L)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", type=Path)
    args = ap.parse_args(argv)
    text = build()
    if args.out:
        args.out.write_text(text + "\n", encoding="utf-8")
        print(f"Wrote {args.out}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
